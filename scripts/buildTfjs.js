const path = require("node:path");
const esbuild = require("esbuild");

const outputPath = path.resolve(__dirname, "../src/vendor/tfjs.cjs");

async function main() {
  await esbuild.build({
    entryPoints: [path.resolve(__dirname, "tfjs-entry.js")],
    bundle: true,
    platform: "node",
    format: "cjs",
    target: "node22",
    minify: true,
    legalComments: "eof",
    outfile: outputPath,
    tsconfigRaw: { compilerOptions: { alwaysStrict: true } },
    logLevel: "warning",
    banner: {
      js: "/* Generated by npm run build:tfjs. Do not edit. See THIRD_PARTY_NOTICES.md. */",
    },
  });

  console.log(`[build:tfjs] Wrote ${path.relative(process.cwd(), outputPath)}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
